 REFF1,VEFF1,REFF2,VEFF2,WV_PACE_REF,MRR1,MRI1,MRR2,MRI2,ARSLND1,ARSLND2, &
 PHYTOPLANKTON_INDEX_REFRACTION,PHYTOPLANKTON_SPECTRAL_SLOPE, &
 SEDIMENT_INDEX_REFRACTION,SEDIMENT_SPECTRAL_SLOPE,WV_BAND,NWV_START,NWV_END)
