CALL h5dclose_f(dset , hdferr)
MRR1_Save(IMIE,NWV_BAND_SEG1P2+NWV_BAND_SEG3+1:NWV_BAND)=HDF5RARR(1:NWV_BAND_SEG4)

HDF5RARR=0.0d0
CALL h5dopen_f (file,'Aerosol_Mif_HARP', dset, hdferr)
