INTEGER FUNCTION INDEX_PRIME_SCATTERING(NTLYERA,TAUR,PNDLY,ARSL_TYPE,WAVELENGTH_NANOMETER)
USE MIE_PHMX_PACE, ONLY : CSCAT_ARSL_BAND
USE PHYSICAL_STATE, ONLY : CEXT_REF,TAU_REF,WV_SEG_FLAG,MONOCHROMATIC_FLAG
USE PACE_INSTRUMENT_DESIGN, ONLY : WV_BAND,NWV_BAND_SEG1,NWV_BAND_SEG1P2,&
                                   NWV_BAND_SEG3,NWV_BAND
IMPLICIT NONE

INTEGER,INTENT(IN) :: NTLYERA
DOUBLE PRECISION,DIMENSION(NTLYERA),INTENT(IN) :: TAUR,PNDLY
INTEGER,DIMENSION(NTLYERA),INTENT(IN) :: ARSL_TYPE
DOUBLE PRECISION,INTENT(IN) :: WAVELENGTH_NANOMETER

INTEGER :: IWV_BAND,ITLYERA
DOUBLE PRECISION:: TAU_SCAT_TOTAL
DOUBLE PRECISION,DIMENSION(:),ALLOCATABLE :: TAULYR
DOUBLE PRECISION :: TAUTMP,TAU_UPPER_LIM
INTEGER,DIMENSION(1) ::LOCINDXTMP

IF((WV_SEG_FLAG==4) .or. (WV_SEG_FLAG<4 .AND. WAVELENGTH_NANOMETER>900D0))THEN

    IF(WV_SEG_FLAG==4) THEN
		LOCINDXTMP =MINLOC(ABS(WAVELENGTH_NANOMETER-WV_BAND(NWV_BAND_SEG1P2+NWV_BAND_SEG3+1:NWV_BAND)))
		IWV_BAND=LOCINDXTMP(1)+NWV_BAND_SEG1P2+NWV_BAND_SEG3
    ELSE
		LOCINDXTMP =MINLOC(ABS(WAVELENGTH_NANOMETER-WV_BAND(NWV_BAND_SEG1+1:NWV_BAND_SEG1P2)))
		IWV_BAND=LOCINDXTMP(1)+NWV_BAND_SEG1
	ENDIF

ELSE
	LOCINDXTMP =MINLOC(ABS(WAVELENGTH_NANOMETER-WV_BAND(1:NWV_BAND_SEG1P2)))
    IWV_BAND=LOCINDXTMP(1)
ENDIF

ALLOCATE(TAULYR(NTLYERA))

DO ITLYERA=1,NTLYERA
  TAULYR(ITLYERA)=PNDLY(ITLYERA)*CSCAT_ARSL_BAND(ARSL_TYPE(ITLYERA),IWV_BAND) + &
                    TAUR(ITLYERA)
ENDDO
TAU_SCAT_TOTAL=SUM(TAULYR)

IF(TAU_SCAT_TOTAL > 2.0D0) THEN
  TAU_UPPER_LIM=1.0D0
ELSE
  TAU_UPPER_LIM=0.5D0*TAU_SCAT_TOTAL
ENDIF

TAUTMP=0.0D0
DO ITLYERA=1,NTLYERA
   TAUTMP=TAUTMP+TAULYR(ITLYERA)
   IF(TAUTMP>=TAU_UPPER_LIM) EXIT
ENDDO
INDEX_PRIME_SCATTERING=ITLYERA
!WRITE(*,*)'INDEX_PRIME_SCATTERING INFO',INDEX_PRIME_SCATTERING,TAUTMP,NTLYERA,TAU_SCAT_TOTAL
DEALLOCATE(TAULYR)
END FUNCTION INDEX_PRIME_SCATTERING


