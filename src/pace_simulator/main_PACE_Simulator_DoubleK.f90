DOUBLE PRECISION FUNCTION FUNCALPHA(ALPHA_VAL)
USE DOUBLEKPARA
IMPLICIT NONE
DOUBLE PRECISION, INTENT(IN) :: ALPHA_VAL
!DOUBLE PRECISION, INTENT(OUT) :: FUNCALPHA_VAL,DFUNCALPHA_VAL

!write(*,*)'Test FUNCALPHA Line 01,', DK(1),DK(2),DK(3),ALPHA_VAL,EXPOFAC

FUNCALPHA=(DK(2)+ALPHA_VAL)**(EXPOFAC+1)-(DK(1)+ALPHA_VAL)*(DK(3)+ALPHA_VAL)**EXPOFAC
!DFUNCALPHA_VAL= (EXPOFAC+1)*(DK(2)+ALPHA_VAL)**EXPOFAC-(DK(3)+ALPHA_VAL)**EXPOFAC &
!			  - EXPOFAC*(DK(1)+ALPHA_VAL)*(DK(3)+ALPHA_VAL)**(EXPOFAC-1)

!write(*,*)'Test FUNCALPHA Line 02',FUNCALPHA_VAL,DFUNCALPHA_VAL

END FUNCTION FUNCALPHA


SUBROUTINE SUB_ALPHA(ALPHA_VAL,FUNCALPHA_VAL,DFUNCALPHA_VAL)
USE DOUBLEKPARA
IMPLICIT NONE
DOUBLE PRECISION, INTENT(IN) :: ALPHA_VAL
DOUBLE PRECISION, INTENT(OUT) :: FUNCALPHA_VAL,DFUNCALPHA_VAL

!write(*,*)'Test FUNCALPHA Line 01,', DK(1),DK(2),DK(3),ALPHA_VAL,EXPOFAC

FUNCALPHA_VAL=(DK(2)+ALPHA_VAL)**(EXPOFAC+1)-(DK(1)+ALPHA_VAL)*(DK(3)+ALPHA_VAL)**EXPOFAC
DFUNCALPHA_VAL= (EXPOFAC+1)*(DK(2)+ALPHA_VAL)**EXPOFAC-(DK(3)+ALPHA_VAL)**EXPOFAC &
              - EXPOFAC*(DK(1)+ALPHA_VAL)*(DK(3)+ALPHA_VAL)**(EXPOFAC-1)

!write(*,*)'Test FUNCALPHA Line 02',FUNCALPHA_VAL,DFUNCALPHA_VAL

END SUBROUTINE SUB_ALPHA

