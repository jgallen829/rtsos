DOUBLE PRECISION :: WAVELENGTH_NANOMETER,RTMP,RTMP1
DOUBLE PRECISION :: ExtX_AEROSOL(0:NUMMIEUSE),ScatX_AEROSOL(0:NUMMIEUSE)
DOUBLE PRECISION,ALLOCATABLE :: RARRAYTMP(:)
INTEGER :: IWV_BAND,nwv_intp_lo,IMIE,MPL,LOCINDXTMP(1)
MPL=3
ALLOCATE(RARRAYTMP(NWV_BAND))
ExtX_AEROSOL=0.0d0
ScatX_AEROSOL=0.0d0

WAVELENGTH_NANOMETER=WAVELENGTH_MICRON*1000.0d0
IF((WV_SEG_FLAG==4) .OR. (WV_SEG_FLAG<4 .AND. WAVELENGTH_NANOMETER>900D0))THEN
    IF(WV_SEG_FLAG==4)THEN
		LOCINDXTMP =MINLOC(ABS(WAVELENGTH_NANOMETER-WV_BAND(NWV_BAND_SEG1P2+NWV_BAND_SEG3+1:NWV_BAND)))
		IWV_BAND=LOCINDXTMP(1)+NWV_BAND_SEG1P2+NWV_BAND_SEG3
    ELSE
		LOCINDXTMP =MINLOC(ABS(WAVELENGTH_NANOMETER-WV_BAND(NWV_BAND_SEG1+1:NWV_BAND_SEG1P2)))
		IWV_BAND=LOCINDXTMP(1)+NWV_BAND_SEG1
    ENDIF
    ExtX_AEROSOL(:)=CEXT_ARSL_BAND(:,IWV_BAND)
	ScatX_AEROSOL(:)=CSCAT_ARSL_BAND(:,IWV_BAND)
ELSE
	LOCINDXTMP =MINLOC(ABS(WAVELENGTH_NANOMETER-WV_BAND(1:NWV_BAND_SEG1)))
    IWV_BAND=LOCINDXTMP(1)
	IF(IWV_BAND==119 .or. IWV_BAND==291 .or. IWV_BAND==341 .or. IWV_BAND==NWV_BAND)THEN
		nwv_intp_lo=IWV_BAND-1
	ELSE
		nwv_intp_lo=IWV_BAND
	ENDIF
	RTMP1=LOG(WV_BAND(nwv_intp_lo+1)/WV_BAND(nwv_intp_lo))

    DO IMIE=1,NUMMIEUSE
        RTMP=LOG(CEXT_ARSL_BAND(IMIE,nwv_intp_lo+1)/CEXT_ARSL_BAND(IMIE,nwv_intp_lo))
		RTMP=RTMP/RTMP1
		ExtX_AEROSOL(IMIE)=CEXT_ARSL_BAND(IMIE,nwv_intp_lo) *                &
                          (WAVELENGTH_NANOMETER/WV_BAND(nwv_intp_lo))**RTMP

        RTMP=LOG(CSCAT_ARSL_BAND(IMIE,nwv_intp_lo+1)/CSCAT_ARSL_BAND(IMIE,nwv_intp_lo))
		RTMP=RTMP/RTMP1
		ScatX_AEROSOL(IMIE)=CSCAT_ARSL_BAND(IMIE,nwv_intp_lo) * &
                          (WAVELENGTH_NANOMETER/WV_BAND(nwv_intp_lo))**RTMP

!        RARRAYTMP=CEXT_ARSL_BAND(IMIE,:)
!		ExtX_AEROSOL(IMIE)=Func_UVIP3P(MPL,WV_BAND(nwv_intp_lo),RARRAYTMP(nwv_intp_lo),WAVELENGTH_NANOMETER,2)
!        RARRAYTMP=CSCAT_ARSL_BAND(IMIE,:)
!        ScatX_AEROSOL(IMIE)=Func_UVIP3P(MPL,WV_BAND(nwv_intp_lo),RARRAYTMP(nwv_intp_lo),WAVELENGTH_NANOMETER,2)
    ENDDO
ENDIF
DEALLOCATE(RARRAYTMP)

CALL PREPARE_RT(Indx_Inelastic_Scattering,IWVSAVE,WAVELENGTH_MICRON,NREC, &
  NTLYERA,NTLYERO,PNDLY,ARSL_TYPE,TAUR,DEPOL_A,TAU_TG,TAU_ARSL_Ext_TMP, &
  TAU_ARSL_Scat_TMP,RECDATASTREAM,NTLYER,NUMMIERT,MAXLORDINPUT,NUMMIEANGINPUT, &
  PHMXDATASTREAM,DELTAM_INPUT,LBDO_LD,FLAM,CHLa,TEMPERTURE,SALINITY, &
  pBRDFa_input,pBRDFk_input,pBRDFb_input,pBRDFe_input,IWV_BAND,ExtX_AEROSOL,ScatX_AEROSOL)
