INTEGER,DIMENSION(NTLYERA),INTENT(IN) :: ARSL_TYPE
INTEGER,DIMENSION(NUMMIERT),INTENT(OUT) :: NUMMIEANGINPUT
DOUBLE PRECISION,DIMENSION(NUMMIERT,NUMMIEANGMAX,0:6),INTENT(OUT) ::PHMXDATASTREAM

DOUBLE PRECISION,DIMENSION(NREC,7),INTENT(OUT) :: RECDATASTREAM

