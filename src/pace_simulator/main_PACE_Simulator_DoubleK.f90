MODULE DOUBLEKPARA
IMPLICIT NONE
INTEGER,PARAMETER :: NDK_CAL=7
LOGICAL :: DOUBLEK_FLAG
DOUBLE PRECISION,DIMENSION(NDK_CAL) :: IMS,DK,GK,EXPOCOEFF
