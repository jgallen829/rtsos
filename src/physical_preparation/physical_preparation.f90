SUBROUTINE COEFFMIXING(NUMMIERT,IPT,MAXLORDINPUT,IWV_BAND,IMIEUSE,TAURfracLOCAL)
USE RTUTILITY, ONLY : SEC_RAD_CORR
USE PHASE_MATRIX_TRUNCATION
USE PHYSICAL_PARTICLES
implicit none

INTEGER,intent(in) :: NUMMIERT,IPT,MAXLORDINPUT,IWV_BAND,IMIEUSE
DOUBLE PRECISION,intent(in) :: TAURfracLOCAL
DOUBLE PRECISION :: RTMP
INTEGER :: LORD,MAXLORD_LOCAL

RTMP=1.0d0-TAURfracLOCAL
FTRUNC(IPT)=RTMP*FTRUNC_ARSL(IMIEUSE,IWV_BAND)
MAXLORD_LOCAL=MIN(2,MAXLORDINPUT)

DO LORD=0,MAXLORD_LOCAL
	BETAL(IPT,LORD) = TAURfracLOCAL*BETAL_Ray_Depol0p029(LORD) + &
						RTMP*BETAL_ARSL(IMIEUSE,IWV_BAND,LORD)
	ALPHAL(IPT,LORD) = TAURfracLOCAL*ALPHAL_Ray_Depol0p029(LORD) +&
						RTMP*ALPHAL_ARSL(IMIEUSE,IWV_BAND,LORD)
	ZETAL(IPT,LORD) = TAURfracLOCAL*ZETAL_Ray_Depol0p029(LORD) +&
						RTMP*ZETAL_ARSL(IMIEUSE,IWV_BAND,LORD)
	DELTAL(IPT,LORD) = TAURfracLOCAL*DELTAL_Ray_Depol0p029(LORD) +&
						RTMP*DELTAL_ARSL(IMIEUSE,IWV_BAND,LORD)
	GAMMAL(IPT,LORD) = TAURfracLOCAL*GAMMAL_Ray_Depol0p029(LORD) +&
						RTMP*GAMMAL_ARSL(IMIEUSE,IWV_BAND,LORD)
	EPSILONL(IPT,LORD) = TAURfracLOCAL*EPSILONL_Ray_Depol0p029(LORD) +&
						RTMP*EPSILONL_ARSL(IMIEUSE,IWV_BAND,LORD)
ENDDO

IF(MAXLORDINPUT>2)THEN
	DO LORD=3,MAXLORDINPUT
		BETAL(IPT,LORD) =RTMP*BETAL_ARSL(IMIEUSE,IWV_BAND,LORD)
		ALPHAL(IPT,LORD) =RTMP* ALPHAL_ARSL(IMIEUSE,IWV_BAND,LORD)
		ZETAL(IPT,LORD) = RTMP*ZETAL_ARSL(IMIEUSE,IWV_BAND,LORD)
		DELTAL(IPT,LORD) =RTMP* DELTAL_ARSL(IMIEUSE,IWV_BAND,LORD)
		GAMMAL(IPT,LORD) =RTMP* GAMMAL_ARSL(IMIEUSE,IWV_BAND,LORD)
		EPSILONL(IPT,LORD) =RTMP* EPSILONL_ARSL(IMIEUSE,IWV_BAND,LORD)
	ENDDO
ENDIF

IF(.NOT. SEC_RAD_CORR) RETURN

NUMORDFULLBETAL(IPT)=NUMBETAL(IMIEUSE)-1
MAXLORD_LOCAL=MIN(2,NUMORDFULLBETAL(IPT))
DO LORD=0,MAXLORD_LOCAL
	FULLBETAL(IPT,LORD)=TAURfracLOCAL*BETAL_Ray_Depol0p029(LORD)+ &
			            RTMP*COEFFMIE_ARSL(IMIEUSE,IWV_BAND,LORD)
ENDDO
IF(NUMORDFULLBETAL(IPT)>2)THEN
	DO LORD=3,NUMORDFULLBETAL(IPT)
		FULLBETAL(IPT,LORD)=RTMP*COEFFMIE_ARSL(IMIEUSE,IWV_BAND,LORD)
	ENDDO
ENDIF

END SUBROUTINE COEFFMIXING

