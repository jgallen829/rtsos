IF(OCEAN_CASE_SELECT==0)THEN
  CPTCLOCAL=APTCLOCAL
  BPTCLOCAL=0.0D0
  BBPTCfracLOCAL=0.0D0 ! BLACK OCEAN
  BBPTCLOCAL=0.0D0     ! BLACK OCEAN
  AWLOCAL=1.0D-6
  BWLOCAL=0.0D0
  BBWLOCAL=0.0D0
ENDIF

CALL WATER_REFRACTIVE_INDEX(WAVELENGTH_NANOMETER,TMPTR,SALINITY,RINDX_WATERLOCAL)

