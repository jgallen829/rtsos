          BETAL_ARSL(IMIEUSE,IWV_BAND,LORD) =BETAL_LOCAL(LORD)
		  ALPHAL_ARSL(IMIEUSE,IWV_BAND,LORD)=ALPHAL_LOCAL(LORD)       !AL2(IL)
		  ZETAL_ARSL(IMIEUSE,IWV_BAND,LORD)=ZETAL_LOCAL(LORD)        !AL3(IL)
		  DELTAL_ARSL(IMIEUSE,IWV_BAND,LORD)=DELTAL_LOCAL(LORD)       !AL4(IL)
		  GAMMAL_ARSL(IMIEUSE,IWV_BAND,LORD)=GAMMAL_LOCAL(LORD)       !BET1(IL)
		  EPSILONL_ARSL(IMIEUSE,IWV_BAND,LORD)=-EPSILONL_LOCAL(LORD)  !BET2(IL)! convention sign change
											  ! double check later
		ENDDO

	ENDDO
	DEALLOCATE(ANG,P11,P12,P22,P33,P34,P44)

ENDDO

DEALLOCATE(BETAL_LOCAL,ALPHAL_LOCAL,ZETAL_LOCAL,DELTAL_LOCAL,&
		   GAMMAL_LOCAL,EPSILONL_LOCAL)

