SUBROUTINE MIECOEFF_TRUNC_MONO(NUMANG,MAXLORDINPUT,DELTAM_INPUT,  &
				ANG,P11,P22,P33,P44,P12,P34,FTRUNC_LOCAL,&
                BETAL_LOCAL,ALPHAL_LOCAL,ZETAL_LOCAL,DELTAL_LOCAL,&
                GAMMAL_LOCAL,EPSILONL_LOCAL)
USE RTTYPE, ONLY : FACTOR,PI
USE PHASE_MATRIX_TRUNCATION, ONLY : ANGLE_TRUNCATION
USE PHYSICAL_PARTICLES, only : NUMBETAL
implicit none
INTEGER,intent(in) :: NUMANG,MAXLORDINPUT,DELTAM_INPUT
INTEGER :: MAXLORDINPUT_LOCAL
DOUBLE PRECISION,DIMENSION(NUMANG),intent(inout) :: ANG,P11,P22,P33,P44,P12,P34
DOUBLE PRECISION,intent(out) :: FTRUNC_LOCAL
DOUBLE PRECISION,DIMENSION(0:MAXLORDINPUT),intent(out) :: BETAL_LOCAL,ALPHAL_LOCAL,ZETAL_LOCAL,DELTAL_LOCAL,&
								   GAMMAL_LOCAL,EPSILONL_LOCAL

INTEGER :: IWV_BAND,IMIEUSE,IANG
INTEGER :: LORD
DOUBLE PRECISION :: MU_LOCAL,RTMP,ANGCUT

DOUBLE PRECISION,DIMENSION(:),ALLOCATABLE :: DL00,DL20,DL2P2,DL2N2
! DELTA FIT DIFINITION

DOUBLE PRECISION,DIMENSION(:),ALLOCATABLE :: TMPL,P11_TRUNC

MAXLORDINPUT_LOCAL=min(MAXLORDINPUT,MAXVAL(NUMBETAL)-1)

ALLOCATE(DL00(0:MAXLORDINPUT_LOCAL),DL20(0:MAXLORDINPUT_LOCAL),DL2P2(0:MAXLORDINPUT_LOCAL),  &
		   DL2N2(0:MAXLORDINPUT_LOCAL))
ALLOCATE(TMPL(0:MAXLORDINPUT_LOCAL),P11_TRUNC(NUMANG))
ANGCUT=COS(ANGLE_TRUNCATION/180.0D0*PI)

BETAL_LOCAL=0.0D0
call bfit(MAXLORDINPUT_LOCAL,NUMANG,ANG,P11,ANGCUT,BETAL_LOCAL,FTRUNC_LOCAL,DELTAM_INPUT)

P11_TRUNC=0.0D0
DO IANG=1,NUMANG
   MU_LOCAL=COS(ANG(IANG)*FACTOR)
   CALL GETDMLlocal(MU_LOCAL,MAXLORDINPUT_LOCAL,DL00,DL20,DL2P2,DL2N2)

	DO LORD=0,MAXLORDINPUT_LOCAL
		P11_TRUNC(IANG)=P11_TRUNC(IANG)+DL00(LORD)*BETAL_LOCAL(LORD)
	ENDDO

	P22(IANG)=P22(IANG)/P11(IANG)*P11_TRUNC(IANG)
	P33(IANG)=P33(IANG)/P11(IANG)*P11_TRUNC(IANG)
	P44(IANG)=P44(IANG)/P11(IANG)*P11_TRUNC(IANG)
	P12(IANG)=P12(IANG)/P11(IANG)*P11_TRUNC(IANG)
	P34(IANG)=P34(IANG)/P11(IANG)*P11_TRUNC(IANG)

ENDDO

! Do Not Change the following part within ***********

DO IANG=1,NUMANG
   RTMP=P22(IANG)
   P22(IANG)=P22(IANG)+P33(IANG)
   P33(IANG)=RTMP-P33(IANG)
ENDDO

ALPHAL_LOCAL=0.0D0
ZETAL_LOCAL=0.0D0
DELTAL_LOCAL=0.0D0
GAMMAL_LOCAL=0.0D0
EPSILONL_LOCAL=0.0D0
call bfit_ger(1,MAXLORDINPUT_LOCAL,NUMANG,ANG,P12,P11_TRUNC,ANGCUT,GAMMAL_LOCAL,DELTAM_INPUT)
call bfit_ger(2,MAXLORDINPUT_LOCAL,NUMANG,ANG,P22,P11_TRUNC,ANGCUT,ALPHAL_LOCAL,DELTAM_INPUT)
call bfit_ger(3,MAXLORDINPUT_LOCAL,NUMANG,ANG,P33,P11_TRUNC,ANGCUT,ZETAL_LOCAL,DELTAM_INPUT)
call bfit_ger(4,MAXLORDINPUT_LOCAL,NUMANG,ANG,P44,P11_TRUNC,ANGCUT,DELTAL_LOCAL,DELTAM_INPUT)
call bfit_ger(5,MAXLORDINPUT_LOCAL,NUMANG,ANG,P34,P11_TRUNC,ANGCUT,EPSILONL_LOCAL,DELTAM_INPUT)
TMPL=ALPHAL_LOCAL
ALPHAL_LOCAL=(ALPHAL_LOCAL+ZETAL_LOCAL)/2.0D0
ZETAL_LOCAL=(TMPL-ZETAL_LOCAL)/2.0D0
! **************************

DEALLOCATE(P11_TRUNC,TMPL,DL00,DL20,DL2P2,DL2N2)

END SUBROUTINE MIECOEFF_TRUNC_MONO

