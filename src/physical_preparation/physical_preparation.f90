SUBROUTINE PREPARE_PARTICLE_COEFFICIENTS(NUMMIEUSE,MAXLORDINPUT,DELTAM_INPUT,NWV_START,NWV_END)
USE RTTYPE, ONLY : FACTOR
USE PHASE_MATRIX_TRUNCATION
USE PHYSICAL_PARTICLES
implicit none
INTEGER,intent(in) :: NUMMIEUSE,MAXLORDINPUT,DELTAM_INPUT
INTEGER :: IWV_BAND,IMIEUSE,IANG
INTEGER :: LORD,NUMANG
INTEGER, INTENT(IN) :: NWV_START,NWV_END
DOUBLE PRECISION :: MU_LOCAL,RTMP

! DELTA FIT DIFINITION
DOUBLE PRECISION,  DIMENSION(:),ALLOCATABLE :: ANG,P11,P12,P22,P33,P34,P44
DOUBLE PRECISION :: FTRUNC_LOCAL
DOUBLE PRECISION,DIMENSION(:),ALLOCATABLE :: BETAL_LOCAL,ALPHAL_LOCAL,ZETAL_LOCAL,DELTAL_LOCAL,&
								   GAMMAL_LOCAL,EPSILONL_LOCAL

ALLOCATE(BETAL_LOCAL(0:MAXLORDINPUT),ALPHAL_LOCAL(0:MAXLORDINPUT),ZETAL_LOCAL(0:MAXLORDINPUT),    &
		 DELTAL_LOCAL(0:MAXLORDINPUT),GAMMAL_LOCAL(0:MAXLORDINPUT),EPSILONL_LOCAL(0:MAXLORDINPUT)  )

DO IMIEUSE=1,NUMMIEUSE
	NUMANG=NUM_SCAT_ANG(IMIEUSE)
	ALLOCATE(ANG(NUMANG),P11(NUMANG),P12(NUMANG),P22(NUMANG),P33(NUMANG),P34(NUMANG),P44(NUMANG))

DO IWV_BAND=NWV_START,NWV_END
		DO IANG=1,NUMANG
		    ANG(IANG)=PHMXMIE_ARSL(IMIEUSE,IWV_BAND,IANG,0)
		    P11(IANG)=PHMXMIE_ARSL(IMIEUSE,IWV_BAND,IANG,1)
			P22(IANG)=PHMXMIE_ARSL(IMIEUSE,IWV_BAND,IANG,2)
			P33(IANG)=PHMXMIE_ARSL(IMIEUSE,IWV_BAND,IANG,3)
			P44(IANG)=PHMXMIE_ARSL(IMIEUSE,IWV_BAND,IANG,4)
			P12(IANG)=PHMXMIE_ARSL(IMIEUSE,IWV_BAND,IANG,5)
			P34(IANG)=PHMXMIE_ARSL(IMIEUSE,IWV_BAND,IANG,6)
		ENDDO

		CALL MIECOEFF_TRUNC_MONO(NUMANG,MAXLORDINPUT,DELTAM_INPUT,  &
			ANG,P11,P22,P33,P44,P12,P34,FTRUNC_LOCAL,&
			BETAL_LOCAL,ALPHAL_LOCAL,ZETAL_LOCAL,DELTAL_LOCAL,&
			GAMMAL_LOCAL,EPSILONL_LOCAL)

