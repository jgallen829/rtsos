SUBROUTINE FFPFCOEFF(BB,NU,DLT90)
USE FOURNIER_FORAND, ONLY : BACKSCATTERING_FRACTION
IMPLICIT NONE
DOUBLE PRECISION BB,NU,DLT90
DOUBLE PRECISION NURTLW,NURTHI,XACC,RTMP
DOUBLE PRECISION,EXTERNAL :: FNU
BACKSCATTERING_FRACTION=BB
NURTLW=-1.0D0
NURTHI=0.0D0
XACC=1.0E-12
CALL bisection(FNU, NURTLW, NURTHI, NU, XACC)
RTMP=(0.01D0-0.3084D0*NU)*(0.01D0-0.3084D0*NU)
DLT90=2.0D0/3.0D0/RTMP
END SUBROUTINE

DOUBLE PRECISION FUNCTION FNU(NU)
USE FOURNIER_FORAND
IMPLICIT NONE
DOUBLE PRECISION NU,BB
DOUBLE PRECISION DLTTMP,RTMP,DLTPNU
BB=BACKSCATTERING_FRACTION
RTMP=(0.01D0-0.3084D0*NU)**2
DLTTMP=2.0D0/3.0D0/RTMP
DLTPNU=DLTTMP**NU
FNU=1.0D0-BB-(0.5D0-DLTTMP*DLTPNU+0.5D0*DLTPNU)/(DLTPNU-DLTTMP*DLTPNU)
END FUNCTION FNU

DOUBLE PRECISION FUNCTION FFPH(NU,DLT90,ANG)
IMPLICIT NONE
DOUBLE PRECISION NU,DLT90,ANG
DOUBLE PRECISION ANGTMP,ANGD2,SINANGD2,COSANG,DLT,DLTPNU,OMDLT,OMDLTPNU
DOUBLE PRECISION FCT1,TRM1,TRM2,DLT180,DLT180PNU,OMDLT180,OMDLT180PNU

ANGTMP=ANG/180.d0*3.1415926535897932d0
IF(ANGTMP<1.0E-4)ANGTMP=1.0E-4
ANGD2=0.5d0*ANGTMP
SINANGD2=SIN(ANGD2)
SINANGD2=SINANGD2*SINANGD2
COSANG=COS(ANGTMP)

DLT180=2.0d0*DLT90
DLT=DLT180*SINANGD2
DLTPNU=DLT**NU
OMDLT=1.0d0-DLT
OMDLTPNU=1.0d0-DLTPNU
FCT1=1.0d0/OMDLT/OMDLT/DLTPNU
TRM1=NU*OMDLT-OMDLTPNU
TRM2=DLT*OMDLTPNU-NU*OMDLT

DLT180PNU=DLT180**NU
OMDLT180=1.0d0-DLT180
OMDLT180PNU=1.0D0-DLT180PNU
FFPH=FCT1*(TRM1+TRM2/SINANGD2)-  &
       0.25d0*OMDLT180PNU/OMDLT180/DLT180PNU*(3.0d0*COSANG*COSANG-1.0d0)
END FUNCTION FFPH

